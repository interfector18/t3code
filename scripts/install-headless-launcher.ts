#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - Host-side launcher installer, not a server service.
import * as NodeFSP from "node:fs/promises";
import * as NodeOS from "node:os";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

type RuntimeSelection = "shared" | "override";

const selectionLines = {
  shared: 'runtime="$(python3 "$managed/runtime.py")"',
  override: 'runtime="${T3CODE_SERVER_RUNTIME:-$(python3 "$managed/runtime.py")}"',
};

function legacyLauncher(selection: RuntimeSelection): string {
  return [
    "#!/bin/sh",
    "set -eu",
    'managed="$HOME/.local/opt/t3code/managed"',
    selectionLines[selection],
    "export ELECTRON_RUN_AS_NODE=1",
    'exec "$runtime/t3code" "$runtime/resources/app.asar/apps/server/dist/bin.mjs" "$@"',
    "",
  ].join("\n");
}

export function renderHeadlessLauncher(selection: RuntimeSelection): string {
  return legacyLauncher(selection).replace(
    "export ELECTRON_RUN_AS_NODE=1",
    [
      "# Generated by scripts/install-headless-launcher.ts; regenerate from that source.",
      'export T3CODE_RESOURCE_MONITOR_PATH="$runtime/resources/resource-monitor/t3-resource-monitor"',
      'if ! test -f "$T3CODE_RESOURCE_MONITOR_PATH" || ! test -x "$T3CODE_RESOURCE_MONITOR_PATH"; then',
      '  printf "Resource monitor is missing or not executable: %s\\n" "$T3CODE_RESOURCE_MONITOR_PATH" >&2',
      "  exit 1",
      "fi",
      "export ELECTRON_RUN_AS_NODE=1",
    ].join("\n"),
  );
}

/** Upgrade only our known launcher forms; preserve custom runtime selection. Never restart. */
export async function installHeadlessLauncher(homeDirectory: string, check = false) {
  const launcher = NodePath.join(homeDirectory, ".local/bin/t3");
  if (!(await NodeFSP.lstat(launcher)).isFile())
    throw new Error(`Not a regular launcher: ${launcher}`);
  const original = await NodeFSP.readFile(launcher, "utf8");
  const selection = (["shared", "override"] as const).find(
    (candidate) =>
      original === legacyLauncher(candidate) || original === renderHeadlessLauncher(candidate),
  );
  if (!selection) throw new Error(`Unrecognized launcher; inspect before replacing ${launcher}`);
  const desired = renderHeadlessLauncher(selection);
  if (check) {
    if (original !== desired) throw new Error("Headless launcher needs regeneration");
    return { launcher, selection, changed: false };
  }
  if (original === desired) return { launcher, selection, changed: false };
  const backupDirectory = await NodeFSP.mkdtemp(
    `${NodePath.join(homeDirectory, ".local/opt/t3code/managed")}/launcher-backup-`,
  );
  await NodeFSP.writeFile(NodePath.join(backupDirectory, "t3"), original, {
    mode: 0o700,
    flag: "wx",
  });
  const temporary = `${launcher}.next-${process.pid}`;
  try {
    await NodeFSP.writeFile(temporary, desired, { mode: 0o755, flag: "wx" });
    if ((await NodeFSP.readFile(launcher, "utf8")) !== original) {
      throw new Error("Launcher changed during installation");
    }
    await NodeFSP.rename(temporary, launcher);
  } finally {
    await NodeFSP.rm(temporary, { force: true });
  }
  return { launcher, selection, changed: true, backupDirectory };
}

if (
  process.argv[1] &&
  NodePath.resolve(process.argv[1]) === NodeURL.fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.some((arg) => arg !== "--check")) {
    throw new Error("Usage: node scripts/install-headless-launcher.ts [--check]");
  }
  console.log(
    JSON.stringify(await installHeadlessLauncher(NodeOS.homedir(), args.includes("--check"))),
  );
}
